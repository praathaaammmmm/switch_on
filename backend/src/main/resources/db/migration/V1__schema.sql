-- Switch On customer backend schema. All timestamps are timestamptz stored in UTC.
-- Money is whole rupees (INR) in integer columns; prices are always computed on the server.

-- ---- Customers and guest identity -------------------------------------------------------------------------
-- A customer is either a guest (identified by an app installation) or, later, a registered account.
-- When OTP login arrives, a guest is merged by pointing merged_into_id at the registered customer and
-- re-parenting rows; nothing here keys on the installation directly, so records survive the merge.
CREATE TABLE customers (
    id              uuid PRIMARY KEY,
    kind            text NOT NULL CHECK (kind IN ('GUEST', 'REGISTERED')),
    display_name    text,
    phone           text,
    email           text,
    merged_into_id  uuid REFERENCES customers (id),
    created_at      timestamptz NOT NULL DEFAULT now()
);

-- The anonymous installation UUID generated by the app on first launch.
CREATE TABLE guest_installations (
    installation_id uuid PRIMARY KEY,
    customer_id     uuid NOT NULL REFERENCES customers (id),
    created_at      timestamptz NOT NULL DEFAULT now()
);

-- Bearer tokens. Only a SHA-256 hash is stored.
CREATE TABLE sessions (
    token_hash      text PRIMARY KEY,
    customer_id     uuid NOT NULL REFERENCES customers (id),
    installation_id uuid REFERENCES guest_installations (installation_id),
    created_at      timestamptz NOT NULL DEFAULT now(),
    last_seen_at    timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX sessions_customer_idx ON sessions (customer_id);

CREATE TABLE addresses (
    id          uuid PRIMARY KEY,
    customer_id uuid NOT NULL REFERENCES customers (id),
    label       text NOT NULL,
    line1       text NOT NULL,
    line2       text NOT NULL DEFAULT '',
    area        text NOT NULL,
    city        text NOT NULL,
    pincode     text NOT NULL CHECK (pincode ~ '^[1-9][0-9]{5}$'),
    landmark    text NOT NULL DEFAULT '',
    is_default  boolean NOT NULL DEFAULT false,
    created_at  timestamptz NOT NULL DEFAULT now(),
    deleted_at  timestamptz
);
CREATE INDEX addresses_customer_idx ON addresses (customer_id) WHERE deleted_at IS NULL;

-- ---- Catalogue ----------------------------------------------------------------------------------------------
CREATE TABLE device_categories (
    code        text PRIMARY KEY,
    label       text NOT NULL,
    sort_order  int  NOT NULL
);

CREATE TABLE device_brands (
    id               serial PRIMARY KEY,
    category_code    text NOT NULL REFERENCES device_categories (code),
    name             text NOT NULL,
    price_multiplier numeric(5, 2) NOT NULL CHECK (price_multiplier > 0),
    sort_order       int NOT NULL,
    UNIQUE (category_code, name)
);

CREATE TABLE device_models (
    id         serial PRIMARY KEY,
    brand_id   int NOT NULL REFERENCES device_brands (id),
    name       text NOT NULL,
    sort_order int NOT NULL,
    UNIQUE (brand_id, name)
);

CREATE TABLE repair_issues (
    code       text PRIMARY KEY,
    label      text NOT NULL,
    hint       text NOT NULL,
    sort_order int  NOT NULL
);

-- What each issue costs on each device. No row means the repair isn't offered for that device.
CREATE TABLE service_catalog_entries (
    category_code   text NOT NULL REFERENCES device_categories (code),
    issue_code      text NOT NULL REFERENCES repair_issues (code),
    base_price_inr  int  NOT NULL CHECK (base_price_inr > 0),
    turnaround      text NOT NULL,
    label_override  text,
    PRIMARY KEY (category_code, issue_code)
);

CREATE TABLE service_areas (
    pincode_prefix text PRIMARY KEY CHECK (pincode_prefix ~ '^[1-9][0-9]{2}$'),
    city           text NOT NULL,
    active         boolean NOT NULL DEFAULT true
);

-- Two-hour pickup windows (start hour in Asia/Kolkata). Availability = capacity minus active bookings.
CREATE TABLE pickup_slot_templates (
    start_hour int PRIMARY KEY CHECK (start_hour BETWEEN 0 AND 22),
    capacity   int NOT NULL CHECK (capacity >= 0)
);

-- Days or windows taken out of service (holidays, full days).
CREATE TABLE pickup_slot_blocks (
    slot_date  date NOT NULL,
    start_hour int  NOT NULL,
    reason     text NOT NULL,
    PRIMARY KEY (slot_date, start_hour)
);

CREATE TABLE repair_shops (
    id             uuid PRIMARY KEY,
    name           text NOT NULL,
    area           text NOT NULL,
    rating         numeric(2, 1) NOT NULL,
    reviews        int NOT NULL,
    technician     text NOT NULL,
    verified_since text NOT NULL
);

CREATE TABLE pickup_partners (
    id      uuid PRIMARY KEY,
    name    text NOT NULL,
    phone   text NOT NULL,
    vehicle text NOT NULL,
    rating  numeric(2, 1) NOT NULL,
    trips   int NOT NULL
);

-- ---- Repairs -------------------------------------------------------------------------------------------------
CREATE TABLE repairs (
    id                  text PRIMARY KEY CHECK (id ~ '^SO-[0-9]{6}$'),
    customer_id         uuid NOT NULL REFERENCES customers (id),
    client_request_id   uuid NOT NULL,
    status              text NOT NULL,
    device_category     text NOT NULL REFERENCES device_categories (code),
    issue_code          text NOT NULL REFERENCES repair_issues (code),
    brand               text,
    model               text,
    symptoms            text[] NOT NULL DEFAULT '{}',
    notes               text NOT NULL DEFAULT '' CHECK (length(notes) <= 300),
    photo_count         int  NOT NULL DEFAULT 0 CHECK (photo_count BETWEEN 0 AND 4),
    estimate_low_inr    int  NOT NULL,
    estimate_high_inr   int  NOT NULL,
    turnaround          text NOT NULL,
    address_id          uuid REFERENCES addresses (id),
    address_snapshot    jsonb NOT NULL,
    slot_date           date NOT NULL,
    slot_start_hour     int  NOT NULL,
    contact_name        text NOT NULL,
    contact_phone       text NOT NULL CHECK (contact_phone ~ '^[6-9][0-9]{9}$'),
    partner_id          uuid REFERENCES pickup_partners (id),
    shop_id             uuid REFERENCES repair_shops (id),
    seal_code           text,
    warranty_claim_for  text REFERENCES repairs (id),
    delivered_at        timestamptz,
    cancelled_at        timestamptz,
    cancel_reason       text,
    created_at          timestamptz NOT NULL DEFAULT now(),
    updated_at          timestamptz NOT NULL DEFAULT now(),
    UNIQUE (customer_id, client_request_id)
);
CREATE INDEX repairs_customer_idx ON repairs (customer_id, created_at DESC);
CREATE INDEX repairs_slot_idx ON repairs (slot_date, slot_start_hour);

-- Append-only history. Rows are never updated or deleted (enforced by the trigger below).
CREATE TABLE repair_status_events (
    id               bigserial PRIMARY KEY,
    repair_id        text NOT NULL REFERENCES repairs (id),
    status           text,
    kind             text NOT NULL CHECK (kind IN ('STATUS', 'CUSTODY', 'PAYMENT', 'NOTE', 'ALERT')),
    title            text NOT NULL,
    customer_message text NOT NULL,
    actor_type       text NOT NULL CHECK (actor_type IN ('CUSTOMER', 'SYSTEM', 'PARTNER', 'SHOP', 'INTERNAL')),
    actor_name       text NOT NULL,
    metadata         jsonb NOT NULL DEFAULT '{}',
    occurred_at      timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX repair_events_repair_idx ON repair_status_events (repair_id, id);

CREATE FUNCTION forbid_event_changes() RETURNS trigger AS $$
BEGIN
    RAISE EXCEPTION 'repair_status_events is append-only';
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER repair_status_events_immutable
    BEFORE UPDATE OR DELETE ON repair_status_events
    FOR EACH ROW EXECUTE FUNCTION forbid_event_changes();

CREATE TABLE handover_records (
    id          uuid PRIMARY KEY,
    repair_id   text NOT NULL REFERENCES repairs (id),
    stage       text NOT NULL CHECK (stage IN ('PICKUP', 'SHOP_INTAKE', 'RETURN', 'DELIVERY')),
    seal_code   text NOT NULL,
    handled_by  text NOT NULL,
    photo_count int  NOT NULL DEFAULT 0,
    seal_intact boolean NOT NULL DEFAULT true,
    occurred_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX handover_repair_idx ON handover_records (repair_id);

CREATE TABLE diagnoses (
    repair_id    text PRIMARY KEY REFERENCES repairs (id),
    summary      text NOT NULL,
    findings     text[] NOT NULL DEFAULT '{}',
    repairable   boolean NOT NULL DEFAULT true,
    diagnosed_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE quotes (
    id             uuid PRIMARY KEY,
    repair_id      text NOT NULL UNIQUE REFERENCES repairs (id),
    warranty_text  text NOT NULL,
    total_inr      int  NOT NULL CHECK (total_inr >= 0),
    sent_at        timestamptz NOT NULL DEFAULT now(),
    decision       text CHECK (decision IN ('APPROVED', 'DECLINED')),
    decided_at     timestamptz,
    decline_reason text,
    CHECK ((decision IS NULL) = (decided_at IS NULL))
);

CREATE TABLE quote_line_items (
    id         uuid PRIMARY KEY,
    quote_id   uuid NOT NULL REFERENCES quotes (id),
    label      text NOT NULL,
    detail     text NOT NULL,
    kind       text NOT NULL CHECK (kind IN ('PART', 'LABOUR', 'FEE')),
    amount_inr int  NOT NULL CHECK (amount_inr >= 0),
    sort_order int  NOT NULL
);

-- At most one payment per repair; the idempotency key makes client retries safe.
CREATE TABLE payment_records (
    id              uuid PRIMARY KEY,
    repair_id       text NOT NULL UNIQUE REFERENCES repairs (id),
    method          text NOT NULL CHECK (method IN ('UPI', 'CARD', 'CASH')),
    amount_inr      int  NOT NULL CHECK (amount_inr > 0),
    reference       text NOT NULL,
    idempotency_key uuid NOT NULL UNIQUE,
    recorded_at     timestamptz NOT NULL DEFAULT now()
);

CREATE SEQUENCE invoice_number_seq START 4000;

CREATE TABLE invoices (
    id          uuid PRIMARY KEY,
    repair_id   text NOT NULL UNIQUE REFERENCES repairs (id),
    invoice_no  text NOT NULL UNIQUE,
    taxable_inr int  NOT NULL,
    cgst_inr    int  NOT NULL,
    sgst_inr    int  NOT NULL,
    total_inr   int  NOT NULL,
    issued_at   timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE warranties (
    repair_id  text PRIMARY KEY REFERENCES repairs (id),
    starts_on  date NOT NULL,
    ends_on    date NOT NULL,
    coverage   text NOT NULL,
    CHECK (ends_on >= starts_on)
);

CREATE TABLE warranty_claims (
    id                 uuid PRIMARY KEY,
    customer_id        uuid NOT NULL REFERENCES customers (id),
    original_repair_id text NOT NULL REFERENCES repairs (id),
    claim_repair_id    text NOT NULL UNIQUE REFERENCES repairs (id),
    problem            text NOT NULL,
    detail             text NOT NULL DEFAULT '',
    status             text NOT NULL CHECK (status IN ('OPEN', 'RESOLVED', 'REJECTED')),
    opened_at          timestamptz NOT NULL DEFAULT now(),
    resolved_at        timestamptz
);
-- Only one open claim per original repair.
CREATE UNIQUE INDEX warranty_claims_one_open ON warranty_claims (original_repair_id) WHERE status = 'OPEN';

CREATE TABLE support_tickets (
    id                text PRIMARY KEY CHECK (id ~ '^TKT-[0-9]{5}$'),
    customer_id       uuid NOT NULL REFERENCES customers (id),
    client_request_id uuid NOT NULL,
    repair_id         text REFERENCES repairs (id),
    topic             text NOT NULL,
    detail            text NOT NULL CHECK (length(detail) BETWEEN 10 AND 500),
    status            text NOT NULL DEFAULT 'OPEN' CHECK (status IN ('OPEN', 'CLOSED')),
    created_at        timestamptz NOT NULL DEFAULT now(),
    UNIQUE (customer_id, client_request_id)
);

-- Metadata only; files live in object storage (not part of this phase).
CREATE TABLE attachments (
    id           uuid PRIMARY KEY,
    customer_id  uuid NOT NULL REFERENCES customers (id),
    repair_id    text REFERENCES repairs (id),
    ticket_id    text REFERENCES support_tickets (id),
    kind         text NOT NULL CHECK (kind IN ('BOOKING_PHOTO', 'HANDOVER_PHOTO', 'TICKET_PHOTO', 'INVOICE_PDF')),
    content_type text NOT NULL,
    size_bytes   bigint NOT NULL CHECK (size_bytes >= 0),
    storage_key  text NOT NULL,
    created_at   timestamptz NOT NULL DEFAULT now()
);
